const iconSize = 12

var iconCache = map[string]*ebiten.Image{} // keyed by name; read with lookups only

// icon returns the named icon as a white-on-transparent image, so it can be
// tinted with a colour scale when drawn.
func icon(name string) *ebiten.Image {
	if img, ok := iconCache[name]; ok {
		return img
	}
	art, ok := iconArt[name]
	if !ok {
		return nil
	}
	img := ebiten.NewImage(iconSize, iconSize)
	for y, row := range strings.Split(strings.TrimSpace(art), "\n") {
		for x, c := range row {
			if c == '#' {
				img.Set(x, y, color.White)
			}
		}
	}
	iconCache[name] = img
	return img
}

// drawIcon draws the named icon with its top-left at (x, y), scaled by s.
func drawIcon(dst *ebiten.Image, name string, x, y, s float64, clr color.Color) {
	img := icon(name)
	if img == nil {
		return
	}
	op := &ebiten.DrawImageOptions{}
	op.GeoM.Scale(s, s)
	op.GeoM.Translate(x, y)
	op.ColorScale.ScaleWithColor(clr)
	dst.DrawImage(img, op)
}
