// Command gen builds the coolproc processor (proc.md) as a mipsim document:
// a gate matrix of NOR gates, laid out by program.
//
//	go run ./coolproc/gen [-o coolproc/cpu.mip] [-program coolproc/demo.asm]
//
// It writes the document and, beside it, prog.bin: the assembled program
// that the program memory loads.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"github.com/Castux/mipsim2/coolproc/isa"
)

func main() {
	output := flag.String("o", "coolproc/cpu.mip", "document to write")
	program := flag.String("program", "coolproc/demo.asm", "program for the program memory")
	flag.Parse()
	if err := run(*output, *program); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run(output, program string) error {
	source, err := os.ReadFile(program)
	if err != nil {
		return err
	}
	words, err := isa.Assemble(string(source))
	if err != nil {
		return fmt.Errorf("%s: %w", program, err)
	}
	document, design, layout, err := ProcessorDocument("prog.bin")
	if err != nil {
		return err
	}
	document.Note = "coolproc: a 16-bit processor generated by coolproc/gen (see proc.md). Pin reset high for a tick, release it, then run the clock: 12 ticks per instruction."
	data, err := document.Save()
	if err != nil {
		return err
	}
	if err := os.WriteFile(output, data, 0o644); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(filepath.Dir(output), "prog.bin"), programImage(words), 0o644); err != nil {
		return err
	}
	fmt.Printf("%s: %d gates, %d transistors, %dx%d cells; program %d words\n",
		output, len(design.gates), design.transistors(), layout.Bounds.Dx(), layout.Bounds.Dy(), len(words))
	return nil
}
