// Command gen builds the coolproc processor (proc.md) as a mipsim document:
// a gate matrix of NOR gates, laid out by program.
//
//	go run ./coolproc/gen [-o coolproc/cpu.mip] [-prog coolproc/demo.asm]
//
// It writes the document and, beside it, prog.bin: the assembled program
// that the ROM loads.
package main

import (
	"flag"
	"fmt"
	"github.com/Castux/mipsim2/coolproc/isa"
	"os"
	"path/filepath"
)

func main() {
	out := flag.String("o", "coolproc/cpu.mip", "document to write")
	prog := flag.String("prog", "coolproc/demo.asm", "program for the ROM")
	flag.Parse()
	if err := run(*out, *prog); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run(out, prog string) error {
	src, err := os.ReadFile(prog)
	if err != nil {
		return err
	}
	words, err := isa.Assemble(string(src))
	if err != nil {
		return fmt.Errorf("%s: %w", prog, err)
	}
	d, c, l, err := CPUDocument("prog.bin")
	if err != nil {
		return err
	}
	d.Note = "coolproc: a 16-bit processor generated by coolproc/gen (see proc.md). Pin reset high for a tick, release it, then run the clock: 12 ticks per instruction."
	data, err := d.Save()
	if err != nil {
		return err
	}
	if err := os.WriteFile(out, data, 0o644); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(filepath.Dir(out), "prog.bin"), romImage(words), 0o644); err != nil {
		return err
	}
	fmt.Printf("%s: %d gates, %d transistors, %dx%d cells; program %d words\n", out, len(c.gates), c.transistors(), l.Bounds.Dx(), l.Bounds.Dy(), len(words))
	return nil
}
